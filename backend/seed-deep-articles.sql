'## 一、参数化知识的三个硬伤

大语言模型把训练语料"压"进权重里，形成一种参数化知识。它足够好用，但在三类场景下会系统性地出问题。

第一是时效性。权重在训练截止那一刻就凝固了，之后发生的事、修订过的规范、新发布的政策，模型一概不知，却仍然会自信地给出答案。

第二是可溯源性。模型输出的是一段流畅文字，而不是"这条结论来自哪份文件的第几节"。在医疗、法务、金融这类需要留痕的场景里，没有出处的答案等于不能用。

第三是私有性。企业内部文档、个人笔记、专有代码库根本不在训练语料里，模型不可能凭空知道。

检索增强生成（Retrieval-Augmented Generation，RAG）针对的正是这三点：不改模型权重，而是在生成前先把相关资料捞出来塞进上下文。

## 二、RAG 的基本形态

一条最朴素的 RAG 链路分三步。

离线阶段，把知识库切块、向量化、存进索引。在线阶段，用户提问后先用检索器取出 Top-K 个相关片段，再把"问题 + 片段"拼成提示词交给大模型，由模型基于片段作答。

Lewis 等人在 2020 年的开创性工作中给出了这个范式的完整形态：参数化记忆是一个预训练的序列到序列模型，非参数化记忆是一个维基百科的稠密向量索引，两者通过可微的检索器连接。他们对比了两种变体——一种在整个生成序列中复用同一批检索结果，另一种可以逐词元切换检索结果——并在多个开放域问答数据集上取得了当时最好的成绩。更重要的是，他们发现 RAG 生成的文本比纯参数化基线更具体、更多样、也更少事实错误。

这个范式的价值在于把"模型知道什么"与"系统能查到什么"解耦了。知识更新不再需要重训模型，只要更新索引；答案的依据也从不可见的权重，变成了可展示、可点击的文档片段。

## 三、检索这一步：从 BM25 到双编码器

检索质量几乎决定了 RAG 的上限。检索不到，后面拼得再漂亮也是无米之炊。

传统做法是稀疏检索，代表是 BM25。它基于词频统计，把查询和文档都表示成高维稀疏词袋向量。优点是无需训练、可解释、对精确术语（产品型号、法条编号）非常敏感。缺点是无法处理同义改写——问"如何退订"检索不到写着"取消订阅"的文档。

稠密检索用双编码器解决这个问题：查询和文档各自过一个编码器，得到低维稠密向量，用余弦相似度比较。Karpukhin 等人提出的 Dense Passage Retrieval（DPR）证明，仅用少量问答对训练的双编码器，就能在多个开放域问答基准上比 Lucene-BM25 的 Top-20 检索准确率高出 9 到 19 个百分点。句向量模型如 Sentence-BERT 进一步把相似度检索的开销从数小时压到数秒，使大规模向量检索在工程上真正可行。

实践中的主流选择是混合检索：先用 BM25 与稠密检索各取一批候选，再合并去重。稀疏负责专有名词和精确匹配，稠密负责语义改写，两者互补而不是替代。评测里只跑其中一种就下结论，是常见的误判来源。

## 四、切块、向量化与索引：工程上最容易出问题的一段

论文里的知识库是干净的维基百科段落，现实中的知识库是 PDF、扫描件、带表格的产品手册和过期的 wiki。绝大部分 RAG 效果问题出在这一段，而不是模型。

切块粒度是最常被低估的超参数。块太小，语义被撕碎，检索到的片段缺少上下文，模型答不完整；块太大，单个块里混进多个主题，向量被"平均"掉，检索精度下降。常见做法是 200 到 500 词元为主、允许相邻块重叠 10% 到 20%，再按标题层级或段落边界切分，而不是机械地按字符数截断。

元数据是第二个容易忽略的点。给每个块打上来源文件、章节标题、更新时间、权限标签，检索时就能做时间和权限过滤，也能在回答里给出可点击的出处链接。没有元数据的 RAG 只能给一堆匿名文本片段，无法溯源。

索引层面，精确近邻搜索在百万级以下尚可暴力计算，规模再大就需要近似最近邻索引（如基于分层可导航小世界图的 HNSW，或 Facebook 开源的 FAISS）。需要留意的是：近似索引会牺牲少量召回率，在小规模上换不来多少加速，不要过早引入。

## 五、检索之后：重排、压缩与引用注入

Top-K 召回的候选集往往"相关但不精准"。这时通常再加一个重排模型：用交叉编码器对"查询-片段"逐对精排，把真正相关的两三条提到最前面。重排模型参数量可以远小于生成模型，但对最终答案质量的提升常常非常明显。

上下文长度有限，还需要做压缩。简单做法是按相关度截断，更好的做法是抽取片段中与问题相关的句子，甚至用一个小模型把长片段改写成短摘要。目标是让进入生成模型的每一段都"有用"，而不是堆满噪音。

提示词的组织同样关键。把检索片段明确标注为"背景资料"，并要求模型"只依据背景资料回答；资料不足时明确说不知道，不要推测"。这样可以把幻觉率显著压低。更进一步是强制引用：要求模型在每句话后面标注片段编号，再用后处理校验编号是否真的存在——这一步能把"看起来有出处"和"真有出处"区分开。

## 六、怎么评估一个 RAG 系统

只看端到端答案的对错，很难定位问题出在检索还是生成。合理的做法是分层评估。

检索层看召回率与排序质量：正确答案所需的片段有没有进 Top-K，排在第几位。生成层看三件事——忠实度（答案是否被检索片段支持）、相关性（是否正面回答了问题）、以及引用准确性（标注的出处是否真的支持那句话）。最后再看端到端任务指标。

需要注意的是，这三个维度经常互相拉扯。把 K 调大能提高召回率，却会把无关内容塞进上下文，反而拉低忠实度。没有分层指标，就只能靠直觉调参。

## 七、几个常见误区

- 以为上了 RAG 就不会幻觉。RAG 降低幻觉但不消除，模型仍可能把片段外的先验知识混进答案，或者曲解片段原意。
- 把所有问题都走检索。闲聊、推理、代码生成这类不需要外部知识的请求，走检索反而会引入干扰。实践中通常加一个路由层判断是否需要检索。
- 只调提示词不看数据。当检索召回率本身只有四成时，优化提示词措辞的收益远小于修好切块和索引。
- 忽视评测集建设。没有一批带标准答案和标准依据的测试问题，任何改动都无法判断是变好还是变坏。

