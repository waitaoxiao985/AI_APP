'## 一、问题的起点：循环网络的顺序瓶颈

在 Transformer 出现之前，序列建模的主流方案是循环神经网络及其变体（LSTM、GRU）。它的处理方式非常直观：模型从左到右逐个读入词元，每一步都把当前词元与上一步的隐状态融合，得到新的隐状态。语义信息像接力棒一样在时间步之间传递。

这种设计有两个结构性代价。第一是训练无法并行：第 t 步的计算必须等第 t-1 步完成，一条长度为 n 的序列就串行地执行 n 次。当 GPU 已经成为算力主体时，串行意味着硬件利用率极低。第二是长程依赖的衰减：信息要跨越几百个时间步才能影响到当前位置，梯度在反向传播时会逐步稀释。LSTM 的门控结构缓解了这个问题，但并没有从根本上改变"信息沿一条链传递"的形态。

2014 年 Bahdanau 等人在机器翻译中引入注意力机制时，指出的正是一个瓶颈：编码器把整个源句压缩成一个固定长度的向量，句子越长信息损失越严重。他们让解码器在生成每个目标词时回头"看"源句的不同位置，按相关性加权取用。这一步很关键——它把"沿链传递"改成了"按需寻址"。

## 二、自注意力：把"看哪里"变成一次矩阵运算

Transformer 的核心洞见是：既然按需寻址有效，那就不必保留循环结构，让序列中的每个位置都直接对所有位置做一次寻址。

具体做法是把每个词元的向量映射成三个角色不同的向量：查询（Query）、键（Key）、值（Value）。查询代表"我在找什么"，键代表"我能提供什么线索"，值代表"我实际携带的内容"。用查询和所有键做点积，得到一组相关性分数；经缩放和 Softmax 归一化后变成权重；再用这组权重对所有值做加权求和，就是该位置的输出。

原论文给出的公式是 Attention(Q, K, V) = softmax(QKᵀ / √d_k) V。分母里的 √d_k 是一个容易被忽略但很关键的细节：当维度 d_k 较大时，点积结果的方差会随维度线性增长，Softmax 会因此进入梯度极小的饱和区。除以 √d_k 把方差拉回常数量级，训练才能稳定。作者同时对比了加性注意力与点积注意力：点积在实现上可以用高度优化的矩阵乘法完成，速度更快。

这一步的复杂度是 O(n²d)，n 是序列长度。看起来比循环的 O(n) 更贵，但由于 n 个位置之间没有依赖，全部可以一次性算完——用空间和算力换并行度，在 GPU 时代是划算的交换。

## 三、多头、位置编码与前馈层

单次注意力只能得到一种"看问题的角度"。多头机制把向量切成 h 个子空间，各自独立做一次注意力，再拼接回原维度。不同头可以分别捕捉句法搭配、指代关系、相邻位置等不同模式。值得注意的是，每个头的维度变小了，总计算量与单头全维度基本持平，也就是说多头几乎是"免费"的。

另一个容易被低估的部分是位置编码。自注意力对输入是置换不变的——打乱词序，输出权重完全一样。为了恢复顺序信息，必须显式地把位置加进去。原始 Transformer 使用固定的正弦余弦函数，好处是理论上可以外推到训练时未见过的长度。后来的工作提出了旋转位置编码（RoPE），把位置信息以旋转矩阵的形式注入注意力内积，对相对位置更友好，目前被多数长上下文模型采用。

前馈层（FFN）常被当作配角，但它承担了相当一部分记忆与知识存储。它的参数量通常占整层的一半以上，作用更像是"对每个位置独立做一次非线性变换"。近年关于知识定位的研究也大多把事实知识关联到前馈层的权重上。

此外还有残差连接与层归一化。残差让梯度可以绕过子层直接回传，是深层网络能够训练的基础；层归一化则把每一层的激活值拉回稳定区间。原论文采用先子层后归一化（Post-LN）的结构，而后续实践发现 Pre-LN 在深层更易训练，如今多数大模型采用 Pre-LN 或其变体。

## 四、两种预训练范式的分叉

Transformer 本身只是一个序列到序列的编码器-解码器架构。真正决定后来格局的，是两种"如何用它做预训练"的路线。

BERT 走的是编码器路线：只用编码器堆叠，训练目标是遮蔽语言模型——随机遮住一部分词元，让模型根据上下文双向预测。因为每个位置都能同时看到左右文，它在理解类任务（分类、抽取、句子匹配）上表现极强。

GPT 走的是解码器路线：只用解码器堆叠，训练目标就是最朴素的"预测下一个词元"。因果掩码保证每个位置只能看到左侧，这让它天然适合文本生成，也天然适合做上下文学习。当参数量和数据量跨过某个规模后，GPT 路线展现出了 BERT 路线没有的能力涌现，此后主流大语言模型几乎都沿着解码器路线发展。

这个分叉值得记住：架构是通用的，真正拉开差距的是训练目标与数据规模。

## 五、读原论文时值得注意的工程细节

